"""Transfer the Engineering Decision Notebook from reports/edn.md into LaTeX.

reports/edn.md is where an EDN entry is written and the only place it is ever
edited (AGENTS.md). This module transfers the entries into reports/latex/edn/,
one `\\ednentry` file per entry, which edn.tex builds into
MLOps_Recommenditos_EDN.pdf. With some seventy entries, most of them with nested
alternatives, links and amendment notes, a transfer by hand would be the slowest
step of a delivery and the one most likely to drift from the source. The
transfer is idempotent: run twice on the same notebook it rewrites nothing, and
run after an edit it changes the files of exactly the entries that changed.

The rule it serves is that the LaTeX is never behind the notebook: whoever
changes reports/edn.md runs `make edn` in the same pull request. `check` changes
nothing and reports what a transfer would change; the required Tests job runs it
as a test on every change to the notebook or its LaTeX, which blocks the merge,
and CI's report job runs it as `--check`. So an entry's **In LaTeX: yes**, which
only the transfer writes, means that the entry is in the PDF exactly as the
notebook states it.

It needs nothing beyond the standard library, so that CI can run the check
without the project environment.

What a run does, in order:

* parses the `## Entries` section of reports/edn.md into entries and fields,
  failing with the entry and the line named when a required field is missing,
  a field appears twice or a line belongs to no field, because a transfer that
  drops text quietly is worse than none;
* renders the Markdown each field holds - the subset the notebook uses, which
  is paragraphs, nested bullet lists, pipe tables, block quotes, and inline
  code, bold, italics, links and autolinks - and refuses what it would not
  render faithfully, such as a fenced code block or a character pdfLaTeX cannot
  typeset, so the failure names the entry instead of a TeX log line;
* writes one file per entry as `edn/NN-slug.tex` and the `\\input` list as
  `edn/entries.tex`, and deletes a generated entry file that no entry produces
  any more (a renamed title changes the slug);
* sets every transferred entry's **In LaTeX** field to `yes` in reports/edn.md,
  adding the field where an entry lacks it, and changes nothing else there.

How the Markdown fields map onto the course's, since the two are not the same:

* The course has no slot for alternatives, so, as reports/latex/README.md says,
  they go into the rationale: first the alternatives with their pros and cons,
  because the rationale argues in terms of them, then the rationale itself.
* A block quote above an entry's fields is how the notebook records that a later
  entry amended this one or that its evidence was corrected. It becomes the
  entry's `note`, which edn.tex prints first, so a reader of the PDF sees that an
  entry was revised before reading what it decided.
* A field the template does not define (EDN-59 has one) is appended to the field
  above it under its own label, so nothing in the source is dropped.
* A field that holds only "-" is the template's "does not apply" and is left out.
* `In LaTeX` is bookkeeping and is not rendered.
* A link to another entry becomes a link inside the PDF, and a relative link to a
  file of the repository becomes its URL on GitHub's `main`, because the PDF is
  read outside the checkout.

An entry whose heading has no fields yet is an ID reserved on `main` before the
branch that needs it was opened (reports/edn.md, "How to add an entry"). It is
skipped with a warning rather than treated as an error, and transferred by the
first run after it has been written.
"""

